'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const ledger=JSON.parse(fs.readFileSync(path.join(root,'src/assets/organs/config.json')));
const provenance=JSON.parse(fs.readFileSync(path.join(root,'design/assets/organ-provenance.json')));
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
test('all twelve source-contained organ atlases preserve traceable sources and embed exact generated bytes',()=>{
 const html=fs.readFileSync(path.join(root,'src/Index.html'),'utf8');
 const first=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0][1];
 const context={window:{}};vm.runInNewContext(first,context);
 const registry=context.window.ASSET_CONFIG.authoredOrgans;
 assert.deepEqual(Object.keys(ledger).sort(),['abyss','myth','recursive','sail','gravity','crystal','manyeyes','abyssshell','parallel','memory','serpent','solar'].sort());
 for(const [id,item] of Object.entries(ledger)){
  assert.ok(item.path.startsWith('src/assets/organs/'),'finished organ outside src');
  assert.ok(['rear','front'].includes(item.display_layer),'missing draw layer');
  const record=provenance[id];
  assert.deepEqual(Object.keys(item).sort(),['path','regions','roots','display_anchor','display_layer'].sort(),'non-implementation metadata in src');
  const source=fs.readFileSync(path.join(root,record.source)),bytes=fs.readFileSync(path.join(root,item.path));
  assert.equal(hash(source),record.source_sha256);
  assert.equal(hash(bytes),record.sha256);
  assert.deepEqual(Buffer.from(registry[id].uri.split(',')[1],'base64'),bytes);
  const [w,h]=[bytes.readUInt32BE(16),bytes.readUInt32BE(20)];
  assert.deepEqual([w,h],record.dimensions);assert.equal(bytes[25],6,'RGBA PNG required');
  assert.equal(item.regions.length,3);assert.equal(item.roots.length,3);
  let end=0;
  for(const [i,[x,y,rw,rh]] of item.regions.entries()){
   assert.ok(x>=end&&y>=0&&rw>0&&rh>0&&x+rw<=w&&y+rh<=h,'invalid/overlapping Lv region');
   const [rx,ry]=item.roots[i];assert.ok(rx>=0&&rx<rw&&ry>=0&&ry<rh,'attachment root outside region');
   end=x+rw;
  }
  assert.match(record.derivation,/not byte-identical crop/);
 }
});
